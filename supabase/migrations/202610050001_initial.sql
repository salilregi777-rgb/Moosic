-- Supabase is the source of truth for Auth, data, and licensed audio uploads.
create table public.profiles (
  id bigint generated by default as identity primary key,
  auth_user_id uuid not null unique references auth.users(id) on delete cascade,
  name text not null check (char_length(name) between 1 and 100),
  username text not null check (char_length(username) between 1 and 32),
  email text not null,
  role text not null default 'user' check (role in ('user', 'manager')),
  is_premium boolean not null default false,
  profile_note text not null default '' check (char_length(profile_note) <= 180),
  created_at timestamptz not null default now()
);
create unique index profiles_username_lower_key on public.profiles(lower(username));
create unique index profiles_email_lower_key on public.profiles(lower(email));

create function public.current_profile_id() returns bigint
language sql stable security definer set search_path = '' as $$
  select id from public.profiles where auth_user_id = (select auth.uid())
$$;
create function public.is_manager() returns boolean
language sql stable security definer set search_path = '' as $$
  select exists(select 1 from public.profiles where auth_user_id = (select auth.uid()) and role = 'manager')
$$;
create function public.has_premium() returns boolean
language sql stable security definer set search_path = '' as $$
  select exists(select 1 from public.profiles where auth_user_id = (select auth.uid()) and is_premium)
$$;
revoke all on function public.current_profile_id(), public.is_manager(), public.has_premium() from public;
grant execute on function public.current_profile_id(), public.is_manager(), public.has_premium() to authenticated;

create function public.handle_new_user() returns trigger
language plpgsql security definer set search_path = '' as $$
declare requested_username text;
begin
  requested_username := left(trim(coalesce(new.raw_user_meta_data ->> 'username', '')), 32);
  if requested_username = '' then requested_username := 'listener_' || left(replace(new.id::text, '-', ''), 20); end if;
  -- User metadata is untrusted: it can never assign role or premium access.
  insert into public.profiles(auth_user_id, name, username, email)
  values (new.id, left(coalesce(nullif(trim(new.raw_user_meta_data ->> 'name'), ''), 'Listener'), 100), requested_username, new.email);
  return new;
end $$;
create trigger on_auth_user_created after insert on auth.users for each row execute function public.handle_new_user();
create function public.sync_profile_email() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  update public.profiles set email = new.email where auth_user_id = new.id;
  return new;
end $$;
create trigger on_auth_email_updated after update of email on auth.users for each row execute function public.sync_profile_email();
revoke all on function public.handle_new_user(), public.sync_profile_email() from public;

