-- Only managers or verified server-side billing may change entitlements.
create function public.manager_set_premium(target_user_id bigint, enabled boolean) returns public.profiles
language plpgsql security definer set search_path = '' as $$
declare result public.profiles;
begin
  if not public.is_manager() then raise exception 'Manager access required' using errcode = '42501'; end if;
  update public.profiles set is_premium = enabled where id = target_user_id and role <> 'manager' returning * into result;
  if not found then raise exception 'User not found or protected manager account' using errcode = 'P0002'; end if;
  return result;
end $$;
create function public.cancel_premium() returns void
language sql security definer set search_path = '' as $$
  update public.profiles set is_premium = false where auth_user_id = (select auth.uid())
$$;
-- Reordering is atomic and verifies the complete set, avoiding partially saved orders.
create function public.reorder_playlist(target_playlist_id bigint, song_ids bigint[]) returns void
language plpgsql security invoker set search_path = '' as $$
declare existing_ids bigint[];
begin
  perform 1 from public.playlists where id = target_playlist_id and user_id = public.current_profile_id() and not is_deleted for update;
  if not found then raise exception 'Playlist not found' using errcode = 'P0002'; end if;
  select coalesce(array_agg(song_id order by song_id), '{}'::bigint[]) into existing_ids from public.playlist_songs where playlist_id = target_playlist_id;
  if existing_ids is distinct from (select coalesce(array_agg(i order by i), '{}'::bigint[]) from unnest(song_ids) as i) then
    raise exception 'song_ids must contain every playlist song exactly once' using errcode = '22023';
  end if;
  update public.playlist_songs p set position = n.position::integer - 1
  from unnest(song_ids) with ordinality as n(song_id, position)
  where p.playlist_id = target_playlist_id and p.song_id = n.song_id;
end $$;
create function public.append_queue(target_song_id bigint) returns public.queue_items
language plpgsql security invoker set search_path = '' as $$
declare result public.queue_items; owner_id bigint := public.current_profile_id();
begin
  perform pg_advisory_xact_lock(owner_id);
  insert into public.queue_items(user_id, song_id, position)
  select owner_id, target_song_id, coalesce(max(position) + 1, 0) from public.queue_items where user_id = owner_id returning * into result;
  return result;
end $$;
revoke all on function public.manager_set_premium(bigint, boolean), public.cancel_premium(), public.reorder_playlist(bigint, bigint[]), public.append_queue(bigint) from public;
grant execute on function public.manager_set_premium(bigint, boolean), public.cancel_premium(), public.reorder_playlist(bigint, bigint[]), public.append_queue(bigint) to authenticated;

